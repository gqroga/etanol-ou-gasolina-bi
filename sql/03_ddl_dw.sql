-- =============================================================
-- 03 - Modelo estrela
-- Grão da fato: 1 preço de 1 produto, em 1 revenda, em 1 data.
-- Toda dimensão tem o membro "Não informado" (sk = -1).
-- Executar como etl.
-- =============================================================

-- ---------- Dimensões ----------

CREATE TABLE IF NOT EXISTS dw.dim_data (
    sk_data          INTEGER PRIMARY KEY,          -- AAAAMMDD
    data             DATE NOT NULL UNIQUE,
    dia              SMALLINT,
    dia_semana       SMALLINT,                     -- 1 = domingo
    nome_dia_semana  VARCHAR(15),
    semana_ano       SMALLINT,
    mes              SMALLINT,
    nome_mes         VARCHAR(15),
    mes_abrev        VARCHAR(3),
    trimestre        SMALLINT,
    semestre         SMALLINT,
    ano              SMALLINT,
    ano_mes          VARCHAR(7),                   -- 'AAAA-MM'
    ano_mes_ordem    INTEGER                       -- AAAAMM, para ordenar no Power BI
);

CREATE TABLE IF NOT EXISTS dw.dim_localidade (
    sk_localidade    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    regiao_sigla     VARCHAR(2),
    regiao_nome      VARCHAR(20),
    uf_sigla         VARCHAR(2),
    uf_nome          VARCHAR(30),
    municipio        VARCHAR(100),
    UNIQUE (uf_sigla, municipio)
);

CREATE TABLE IF NOT EXISTS dw.dim_revenda (
    sk_revenda       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cnpj             CHAR(14) NOT NULL UNIQUE,     -- chave natural, só dígitos
    razao_social     VARCHAR(200),
    bairro           VARCHAR(100),
    cep              CHAR(8)
);

CREATE TABLE IF NOT EXISTS dw.dim_produto (
    sk_produto       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto          VARCHAR(50) NOT NULL UNIQUE,
    grupo_produto    VARCHAR(20),                  -- GASOLINA / ETANOL / DIESEL / GNV
    unidade_medida   VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS dw.dim_bandeira (
    sk_bandeira      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bandeira         VARCHAR(100) NOT NULL UNIQUE,
    tipo_bandeira    VARCHAR(20)                   -- 'Bandeira branca' / 'Distribuidora'
);

-- Membros "Não informado"
INSERT INTO dw.dim_data (sk_data, data, ano_mes, nome_mes) VALUES (-1, DATE '1900-01-01', 'N/I', 'Não informado') ON CONFLICT DO NOTHING;
INSERT INTO dw.dim_localidade (sk_localidade, regiao_nome, uf_nome, municipio) VALUES (-1, 'Não informado', 'Não informado', 'NÃO INFORMADO') ON CONFLICT DO NOTHING;
INSERT INTO dw.dim_revenda (sk_revenda, cnpj, razao_social) VALUES (-1, '00000000000000', 'NÃO INFORMADO') ON CONFLICT DO NOTHING;
INSERT INTO dw.dim_produto (sk_produto, produto, grupo_produto) VALUES (-1, 'NÃO INFORMADO', 'N/I') ON CONFLICT DO NOTHING;
INSERT INTO dw.dim_bandeira (sk_bandeira, bandeira, tipo_bandeira) VALUES (-1, 'NÃO INFORMADO', 'N/I') ON CONFLICT DO NOTHING;

-- ---------- Fato ----------

CREATE TABLE IF NOT EXISTS dw.fato_coleta_preco (
    sk_data          INTEGER NOT NULL REFERENCES dw.dim_data,
    sk_localidade    INTEGER NOT NULL REFERENCES dw.dim_localidade,
    sk_revenda       INTEGER NOT NULL REFERENCES dw.dim_revenda,
    sk_produto       INTEGER NOT NULL REFERENCES dw.dim_produto,
    sk_bandeira      INTEGER NOT NULL REFERENCES dw.dim_bandeira,
    valor_venda      NUMERIC(10,3),
    valor_compra     NUMERIC(10,3),
    fl_outlier       SMALLINT NOT NULL DEFAULT 0,
    arquivo_origem   VARCHAR(100)
);

-- O índice único garante o grão: se o ETL deixar passar duplicata, a carga falha.
CREATE UNIQUE INDEX IF NOT EXISTS ux_fato_grao
    ON dw.fato_coleta_preco (sk_revenda, sk_produto, sk_data);
CREATE INDEX IF NOT EXISTS ix_fato_data    ON dw.fato_coleta_preco (sk_data);
CREATE INDEX IF NOT EXISTS ix_fato_produto ON dw.fato_coleta_preco (sk_produto);

-- ---------- Log de carga (validações do job) ----------

CREATE TABLE IF NOT EXISTS dw.log_carga (
    id_log           INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    dt_execucao      TIMESTAMP DEFAULT now(),          -- igual para todas as linhas de uma execução
    verificacao      VARCHAR(100),
    valor            BIGINT,
    ok               BOOLEAN
);
